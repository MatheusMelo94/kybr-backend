#!/usr/bin/env bash
# One-command local dev: MongoDB (compose, single-node replica set rs0) + the API with the "local" profile.
#
#   ./run-local.sh            start Mongo in Docker, then ./mvnw spring-boot:run (profile local)
#   ./run-local.sh --no-mongo skip Docker; use MONGODB_URI from the environment or .env (must be a replica set)
#   ./run-local.sh --docker   run the full containerised stack instead (docker compose up --build, profile docker)
#   ./run-local.sh --down     stop the compose stack (keeps the Mongo volume)
#   ./run-local.sh --secrets  only make sure .env holds the dev secrets, then exit (used by CI)
#
# Optional overrides: a gitignored .env (copy .env.example). Only non-empty KEY=value lines are exported.
# First run: the profiles have no secret defaults, so any of KYBR_BFF_KEY_CURRENT, KYBR_HASH_SECRET,
# KYBR_IDEMPOTENCY_ENC_KEY, KYBR_PII_ENC_KEY and KYBR_ADMIN_TOKEN that is unset gets a random dev value
# appended to .env (existing values are never changed). Generated by the test-classpath DevEnvSecrets,
# so it needs JDK 25 even with --docker.
set -euo pipefail

cd "$(dirname "$0")"

die() { echo "run-local: $*" >&2; exit 1; }

load_env_file() {
  [ -f .env ] || return 0
  local line key val
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; esac
    key=${line%%=*}
    val=${line#*=}
    [[ $key =~ ^[A-Z_][A-Z0-9_]*$ ]] || continue
    [ -n "$val" ] || continue
    export "$key=$val"
  done < .env
}

require_compose() {
  command -v docker >/dev/null 2>&1 || die "docker not found (use --no-mongo with an external replica-set MONGODB_URI)"
  docker compose version >/dev/null 2>&1 || die "docker compose v2 not found"
}

require_java25() {
  command -v java >/dev/null 2>&1 || die "java not found; install a JDK 25 (e.g. Temurin 25)"
  local v
  v=$(java -XshowSettings:properties -version 2>&1 | awk -F'= ' '/java.specification.version/ {print $2}')
  [ "${v%%.*}" -ge 25 ] 2>/dev/null || die "JDK 25+ required (found java.specification.version=${v:-unknown})"
}

DEV_SECRETS=(KYBR_BFF_KEY_CURRENT KYBR_HASH_SECRET KYBR_IDEMPOTENCY_ENC_KEY KYBR_PII_ENC_KEY KYBR_ADMIN_TOKEN)

env_file_has() { [ -f .env ] && grep -Eq "^$1=.+" .env; }

# $1 = env: a value in the environment (which load_env_file filled from .env) counts as set.
# $1 = file: only .env counts (compose passes .env to the container, not the shell environment).
ensure_dev_secrets() {
  local missing=() key out line
  for key in "${DEV_SECRETS[@]}"; do
    if [ "$1" = env ] && [ -n "${!key:-}" ]; then continue; fi
    env_file_has "$key" || missing+=("$key")
  done
  [ ${#missing[@]} -gt 0 ] || return 0
  require_java25
  [ -x ./mvnw ] || die "./mvnw not found or not executable"
  echo "run-local: generating dev secrets into .env: ${missing[*]}"
  ./mvnw -q -B test-compile dependency:build-classpath -Dmdep.includeScope=test \
    -Dmdep.outputFile=target/dev-classpath.txt >/dev/null
  out=$(java -cp "target/test-classes:target/classes:$(cat target/dev-classpath.txt)" \
    com.matheusmelo.kybr.support.DevEnvSecrets) || die "dev secret generation failed"
  [ -f .env ] || (umask 077 && : > .env)
  if [ -s .env ] && [ -n "$(tail -c1 .env)" ]; then echo >> .env; fi
  for key in "${missing[@]}"; do
    line=$(printf '%s\n' "$out" | grep -E "^$key=.+") || die "generator printed no $key"
    printf '%s\n' "$line" >> .env
  done
}

mode=${1:-}
case "$mode" in
  --down)
    require_compose
    exec docker compose down
    ;;
  --secrets)
    ensure_dev_secrets file
    exit 0
    ;;
  --docker)
    require_compose
    ensure_dev_secrets file
    exec docker compose up --build
    ;;
  --no-mongo)
    load_env_file
    [ -n "${MONGODB_URI:-}" ] || die "--no-mongo needs MONGODB_URI (in the environment or .env)"
    ensure_dev_secrets env
    load_env_file
    ;;
  '')
    load_env_file
    ensure_dev_secrets env
    load_env_file
    require_compose
    echo "run-local: starting MongoDB (rs0) ..."
    docker compose up -d --wait mongo
    ;;
  *)
    die "unknown option: $mode (see the header of this script)"
    ;;
esac

require_java25
[ -x ./mvnw ] || die "./mvnw not found or not executable"
echo "run-local: API on http://localhost:${PORT:-8080} (liveness: /livez), management on :${MANAGEMENT_PORT:-8081}"
exec ./mvnw -B spring-boot:run -Dspring-boot.run.profiles=local
